import dotenv from 'dotenv';
import path from 'path';

// Load .env
dotenv.config({ path: path.resolve(__dirname, '../.env') });

import WebSocket from 'ws';
import { generateDhanTOTP, autoGenerateDhanToken, getTokenExpiryMinutes } from '../server/src/utils/dhanTokenRefresh';

async function runConnectivityTest() {
  console.log('========================================================');
  console.log('   DHAN HQ API CONNECTIVITY & HEALTH PRE-FLIGHT TEST    ');
  console.log('========================================================');
  console.log(`Current Time (IST): ${new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}`);

  const clientId = process.env.DHAN_CLIENT_ID;
  const pin = process.env.DHAN_PIN;
  const totpSecret = process.env.DHAN_TOTP_SECRET;
  let accessToken = process.env.DHAN_ACCESS_TOKEN || '';

  console.log(`\n1. Credential Check:`);
  console.log(`   - Client ID:    ${clientId ? '✅ ' + clientId : '❌ MISSING'}`);
  console.log(`   - PIN:          ${pin ? '✅ Set (' + pin.length + ' chars)' : '❌ MISSING'}`);
  console.log(`   - TOTP Secret:  ${totpSecret ? '✅ Set (' + totpSecret.substring(0, 6) + '...)' : '❌ MISSING'}`);
  console.log(`   - Access Token: ${accessToken ? '✅ Present (' + accessToken.substring(0, 15) + '...)' : '❌ MISSING'}`);

  if (totpSecret) {
    const sampleTotp = generateDhanTOTP(totpSecret);
    console.log(`   - Generated Live TOTP: ${sampleTotp} (RFC 6238 OK)`);
  }

  // Token Expiry Check
  let minutesLeft = accessToken ? getTokenExpiryMinutes(accessToken) : -1;
  console.log(`\n2. Token Validity:`);
  if (minutesLeft > 0) {
    console.log(`   - Minutes remaining: ${minutesLeft} (~${(minutesLeft / 60).toFixed(1)} hours)`);
  } else {
    console.log(`   - Token Status: EXPIRED / INVALID (${minutesLeft} mins)`);
  }

  // If token expired or close to expiry, attempt auto-renewal
  if (minutesLeft <= 15) {
    console.log(`\n🔄 Attempting automated token refresh via Dhan Auth API...`);
    const renewRes = await autoGenerateDhanToken(clientId, pin, totpSecret);
    if (renewRes.success && renewRes.accessToken) {
      accessToken = renewRes.accessToken;
      minutesLeft = getTokenExpiryMinutes(accessToken);
      console.log(`   ✅ Successfully renewed token! Valid for ${minutesLeft} minutes.`);
    } else {
      console.log(`   ❌ Token renewal failed: ${renewRes.message}`);
    }
  }

  // Test REST API Quote Endpoint
  console.log(`\n3. Testing REST Marketfeed Endpoint (https://api.dhan.co/v2/marketfeed/quote):`);
  try {
    const quoteRes = await fetch('https://api.dhan.co/v2/marketfeed/quote', {
      method: 'POST',
      headers: {
        'access-token': accessToken,
        'client-id': clientId || '',
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        IDX_I: [13, 25, 51] // NIFTY, BANKNIFTY, SENSEX
      }),
      signal: AbortSignal.timeout(6000)
    });

    const quoteStatus = quoteRes.status;
    const quoteData: any = await quoteRes.json().catch(() => null);

    if (quoteRes.ok && quoteData) {
      console.log(`   ✅ REST Quote Request Successful (HTTP ${quoteStatus})`);
      if (quoteData.data) {
        console.log(`   Data received:`, JSON.stringify(quoteData.data, null, 2).substring(0, 300) + '...');
      } else {
        console.log(`   Response:`, quoteData);
      }
    } else {
      console.log(`   ⚠️ REST Quote Request returned HTTP ${quoteStatus}:`, quoteData);
    }
  } catch (err: any) {
    console.error(`   ❌ REST Quote Request failed:`, err.message);
  }

  // Test WebSocket Feed Connectivity
  console.log(`\n4. Testing WebSocket Feed (wss://api-feed.dhan.co):`);
  const wsUrl = `wss://api-feed.dhan.co?version=2&token=${encodeURIComponent(accessToken)}&clientId=${encodeURIComponent(clientId || '')}&authType=2`;

  await new Promise<void>((resolve) => {
    let closed = false;
    const ws = new WebSocket(wsUrl);

    const timer = setTimeout(() => {
      if (!closed) {
        console.log(`   ⏱️ WebSocket test timed out after 10s (Mock trading session may not have started yet, or market feed is idle).`);
        try { ws.terminate(); } catch (_) {}
        resolve();
      }
    }, 10000);

    ws.on('open', () => {
      console.log(`   ✅ WebSocket Connection Established!`);
      // Send subscription for NIFTY (13), BANKNIFTY (25), SENSEX (51)
      const subPayload = JSON.stringify({
        RequestCode: 15,
        InstrumentCount: 3,
        InstrumentList: [
          { ExchangeSegment: 'IDX_I', SecurityId: '13' },
          { ExchangeSegment: 'IDX_I', SecurityId: '25' },
          { ExchangeSegment: 'IDX_I', SecurityId: '51' }
        ]
      });
      console.log(`   📡 Sent subscription request for NIFTY, BANKNIFTY, SENSEX...`);
      ws.send(subPayload);
    });

    let ticksReceived = 0;
    ws.on('message', (data: WebSocket.Data) => {
      ticksReceived++;
      if (ticksReceived <= 3) {
        if (Buffer.isBuffer(data)) {
          const responseCode = data.readUInt8(0);
          const msgLen = data.readUInt16LE(1);
          console.log(`   📥 Received Binary Packet #${ticksReceived}: ResponseCode=${responseCode}, MsgLen=${msgLen}, TotalBytes=${data.length}`);
        } else {
          console.log(`   📥 Received Text Message #${ticksReceived}:`, data.toString().substring(0, 150));
        }
      }
      if (ticksReceived === 5) {
        console.log(`   🎉 Received ${ticksReceived} ticks successfully! WebSocket pipeline is verified.`);
        closed = true;
        clearTimeout(timer);
        ws.close();
        resolve();
      }
    });

    ws.on('error', (err) => {
      console.error(`   ❌ WebSocket Error:`, err.message);
    });

    ws.on('close', (code, reason) => {
      if (!closed) {
        console.log(`   ℹ️ WebSocket Closed (Code: ${code}, Reason: "${reason.toString() || 'None'}")`);
        clearTimeout(timer);
        resolve();
      }
    });
  });

  console.log('\n========================================================');
  console.log('                 PRE-FLIGHT TEST COMPLETE               ');
  console.log('========================================================\n');
}

runConnectivityTest().catch((err) => {
  console.error('Fatal test error:', err);
  process.exit(1);
});
