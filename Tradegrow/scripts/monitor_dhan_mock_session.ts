import dotenv from 'dotenv';
import path from 'path';
import fs from 'fs';

// Load .env
dotenv.config({ path: path.resolve(__dirname, '../.env') });

import WebSocket from 'ws';
import { autoGenerateDhanToken, getTokenExpiryMinutes } from '../server/src/utils/dhanTokenRefresh';

interface InstrumentInfo {
  token: string;
  segment: string;
  securityId: string;
  name: string;
}

const MONITORED_INSTRUMENTS: InstrumentInfo[] = [
  { token: 'NSE_NIFTY50', segment: 'IDX_I', securityId: '13', name: 'NIFTY 50' },
  { token: 'NSE_BANKNIFTY', segment: 'IDX_I', securityId: '25', name: 'BANK NIFTY' },
  { token: 'BSE_SENSEX', segment: 'IDX_I', securityId: '51', name: 'SENSEX' },
  { token: 'NSE_FINNIFTY', segment: 'IDX_I', securityId: '27', name: 'FIN NIFTY' },
  { token: 'NSE_MIDCPNIFTY', segment: 'IDX_I', securityId: '33', name: 'MIDCP NIFTY' },
  { token: 'NSE_RELIANCE', segment: 'NSE_EQ', securityId: '2885', name: 'RELIANCE' },
  { token: 'NSE_HDFCBANK', segment: 'NSE_EQ', securityId: '1333', name: 'HDFC BANK' },
  { token: 'NSE_TCS', segment: 'NSE_EQ', securityId: '11536', name: 'TCS' },
  { token: 'NSE_INFY', segment: 'NSE_EQ', securityId: '1594', name: 'INFOSYS' }
];

const SECURITY_ID_MAP = new Map<string, InstrumentInfo>();
MONITORED_INSTRUMENTS.forEach(i => SECURITY_ID_MAP.set(i.securityId, i));

// Session Metrics State
const stats = {
  sessionStartTime: Date.now(),
  connectedAt: 0,
  reconnectCount: 0,
  isConnected: false,
  totalTicks: 0,
  windowTicks: 0,
  peakTickRate: 0,
  lastTickTimestamp: 0,
  packetCodeCounts: {} as Record<number, number>,
  corruptPackets: 0,
  lastPrices: {} as Record<string, { ltp: number; time: string; change?: number }>,
  latenciesMs: [] as number[],
  errors: [] as string[]
};

const LOG_DIR = path.resolve(__dirname, '../logs');
if (!fs.existsSync(LOG_DIR)) {
  fs.mkdirSync(LOG_DIR, { recursive: true });
}
const LOG_FILE = path.join(LOG_DIR, `dhan_mock_session_${new Date().toISOString().split('T')[0]}.log`);

function logBoth(msg: string) {
  const line = `[${new Date().toLocaleTimeString('en-IN', { timeZone: 'Asia/Kolkata' })}] ${msg}`;
  console.log(line);
  fs.appendFileSync(LOG_FILE, line + '\n');
}

async function startSessionMonitor() {
  console.clear();
  logBoth('========================================================================');
  logBoth('       DHAN HQ INFRASTRUCTURE UPGRADE & MOCK SESSION MONITOR (LIVE)    ');
  logBoth('                     Window: 11:00 AM - 3:00 PM IST                     ');
  logBoth('========================================================================');

  const clientId = process.env.DHAN_CLIENT_ID;
  const pin = process.env.DHAN_PIN;
  const totpSecret = process.env.DHAN_TOTP_SECRET;
  let accessToken = process.env.DHAN_ACCESS_TOKEN || '';

  // Check token expiry
  let minutesLeft = getTokenExpiryMinutes(accessToken);
  if (minutesLeft <= 30) {
    logBoth(`🔑 Dhan token near expiry (${minutesLeft}m left). Triggering auto-renewal...`);
    const res = await autoGenerateDhanToken(clientId, pin, totpSecret);
    if (res.success && res.accessToken) {
      accessToken = res.accessToken;
      logBoth(`✅ Successfully renewed token via TOTP.`);
    } else {
      logBoth(`⚠️ Token renewal failed: ${res.message}. Proceeding with existing token.`);
    }
  } else {
    logBoth(`✅ Token validated. Expires in ${minutesLeft} minutes (~${(minutesLeft/60).toFixed(1)}h).`);
  }

  let ws: WebSocket | null = null;
  let pingTimer: NodeJS.Timeout | null = null;
  let isShuttingDown = false;

  function connect() {
    if (isShuttingDown) return;

    stats.isConnected = false;
    const wsUrl = `wss://api-feed.dhan.co?version=2&token=${encodeURIComponent(accessToken)}&clientId=${encodeURIComponent(clientId || '')}&authType=2`;
    logBoth(`🌐 Connecting to Dhan WebSocket Feed (Attempt #${stats.reconnectCount + 1})...`);

    ws = new WebSocket(wsUrl);

    ws.on('open', () => {
      stats.isConnected = true;
      stats.connectedAt = Date.now();
      logBoth(`🟢 WebSocket Connected Successfully!`);

      // Send subscriptions
      const instrumentList = MONITORED_INSTRUMENTS.map(i => ({
        ExchangeSegment: i.segment,
        SecurityId: i.securityId
      }));

      const subPayload = JSON.stringify({
        RequestCode: 15, // Ticker feed
        InstrumentCount: instrumentList.length,
        InstrumentList: instrumentList
      });

      ws?.send(subPayload);
      logBoth(`📡 Subscribed to ${instrumentList.length} instruments (${MONITORED_INSTRUMENTS.map(i => i.name).join(', ')})`);

      // 20s Ping interval
      if (pingTimer) clearInterval(pingTimer);
      pingTimer = setInterval(() => {
        if (ws && ws.readyState === WebSocket.OPEN) {
          try { ws.ping(); } catch (_) {}
        }
      }, 20000);
    });

    ws.on('message', (data: WebSocket.Data) => {
      stats.lastTickTimestamp = Date.now();
      stats.totalTicks++;
      stats.windowTicks++;

      if (Buffer.isBuffer(data)) {
        parseBinaryBuffer(data);
      } else {
        logBoth(`ℹ️ Text frame received: ${data.toString().substring(0, 100)}`);
      }
    });

    ws.on('error', (err: Error) => {
      stats.isConnected = false;
      const errMsg = `WebSocket Error: ${err.message}`;
      stats.errors.push(errMsg);
      logBoth(`🔴 ${errMsg}`);
    });

    ws.on('close', (code: number, reason: Buffer) => {
      stats.isConnected = false;
      if (pingTimer) clearInterval(pingTimer);
      logBoth(`⚠️ Connection closed (code: ${code}, reason: "${reason.toString() || 'none'}").`);
      
      if (!isShuttingDown) {
        stats.reconnectCount++;
        const backoff = Math.min(2000 * Math.pow(1.5, Math.min(stats.reconnectCount, 5)), 15000);
        logBoth(`⏳ Reconnecting in ${(backoff / 1000).toFixed(1)}s...`);
        setTimeout(connect, backoff);
      }
    });
  }

  function parseBinaryBuffer(buf: Buffer) {
    if (buf.length < 8) {
      stats.corruptPackets++;
      return;
    }

    let offset = 0;
    while (offset + 8 <= buf.length) {
      const responseCode = buf.readUInt8(offset);
      const msgLen = buf.readUInt16LE(offset + 1);
      const securityId = buf.readInt32LE(offset + 4).toString();

      stats.packetCodeCounts[responseCode] = (stats.packetCodeCounts[responseCode] || 0) + 1;

      const packetLen = msgLen >= 8 ? msgLen : (
        responseCode === 2 ? 16 :
        responseCode === 4 ? 50 :
        responseCode === 6 ? 12 :
        responseCode === 7 ? 50 :
        responseCode === 8 ? 184 : 8
      );

      const inst = SECURITY_ID_MAP.get(securityId);
      if (inst) {
        let ltp = 0;
        if (responseCode === 2 && offset + 12 <= buf.length) {
          ltp = buf.readFloatLE(offset + 8);
        } else if ((responseCode === 4 || responseCode === 7 || responseCode === 8) && offset + 16 <= buf.length) {
          ltp = buf.readFloatLE(offset + 8);
        } else if (responseCode === 6 && offset + 12 <= buf.length) {
          ltp = buf.readFloatLE(offset + 8);
        }

        if (ltp > 0) {
          stats.lastPrices[inst.name] = {
            ltp: Number(ltp.toFixed(2)),
            time: new Date().toLocaleTimeString('en-IN', { timeZone: 'Asia/Kolkata' })
          };
        }
      }

      offset += Math.max(8, packetLen);
    }
  }

  // Dashboard refresh interval (every 5 seconds)
  const dashboardInterval = setInterval(() => {
    const elapsedSec = Math.floor((Date.now() - stats.sessionStartTime) / 1000);
    const elapsedStr = `${Math.floor(elapsedSec / 3600)}h ${Math.floor((elapsedSec % 3600) / 60)}m ${elapsedSec % 60}s`;
    const curRate = (stats.windowTicks / 5).toFixed(1);
    if (Number(curRate) > stats.peakTickRate) stats.peakTickRate = Number(curRate);
    stats.windowTicks = 0;

    const timeSinceLastTick = stats.lastTickTimestamp > 0 
      ? `${((Date.now() - stats.lastTickTimestamp) / 1000).toFixed(1)}s ago`
      : 'No ticks yet';

    console.log('\n------------------------------------------------------------------------');
    console.log(`⏱️ Elapsed: ${elapsedStr} | Status: ${stats.isConnected ? '🟢 CONNECTED' : '🔴 DISCONNECTED'} | Reconnects: ${stats.reconnectCount}`);
    console.log(`📊 Total Ticks: ${stats.totalTicks.toLocaleString()} | Rate: ${curRate} ticks/sec | Peak: ${stats.peakTickRate} t/s | Last Tick: ${timeSinceLastTick}`);
    console.log(`📦 Packet Codes: ${JSON.stringify(stats.packetCodeCounts)} | Corrupted: ${stats.corruptPackets}`);
    
    // Print Price Snapshots
    const priceEntries = Object.entries(stats.lastPrices);
    if (priceEntries.length > 0) {
      console.log('📈 Live Ticks: ' + priceEntries.map(([name, p]) => `${name}: ₹${p.ltp.toFixed(2)}`).join(' | '));
    }
    console.log('------------------------------------------------------------------------');
  }, 5000);

  // Initial connection
  connect();

  // Handle graceful exit
  process.on('SIGINT', () => {
    isShuttingDown = true;
    clearInterval(dashboardInterval);
    if (pingTimer) clearInterval(pingTimer);
    if (ws) {
      try { ws.close(); } catch (_) {}
    }
    logBoth('\n🛑 Session Monitor stopped by user.');
    logBoth(`Summary: Total Ticks=${stats.totalTicks}, Reconnects=${stats.reconnectCount}, PeakRate=${stats.peakTickRate} t/s`);
    logBoth(`Full session log saved to: ${LOG_FILE}`);
    process.exit(0);
  });
}

startSessionMonitor().catch(err => {
  console.error('Fatal Monitor Error:', err);
});
