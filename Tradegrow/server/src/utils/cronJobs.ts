/**
 * Start the Dhan token expiry check interval.
 * Checks every 30 minutes. Sends an alert if token expires in <60 minutes.
 */
function startTokenExpiryCheck(getAccessToken: () => string) {
  // Run immediately on start
  const checkNow = async () => {
    const token = getAccessToken();
    const hasAutoCreds = process.env.DHAN_TOTP_SECRET && process.env.DHAN_PIN && process.env.DHAN_CLIENT_ID;

    // Check if token missing or expiring in <60 min
    const isExpiring = !token || isTokenExpiringSoon(token, 60);

    if (isExpiring) {
      if (hasAutoCreds) {
        console.log('[CronJobs] 🔄 Dhan token missing or expiring soon. Attempting automated renewal with TOTP...');
        const res = await autoGenerateDhanToken();
        if (res.success) {
          console.log('[CronJobs] ✅ Dhan token auto-generated & updated successfully!');
          return;
        } else {
          console.warn('[CronJobs] ⚠️ Dhan auto-generation failed:', res.message);
        }
      }

      if (token) {
        const minutesLeft = getTokenExpiryMinutes(token);
        console.warn(`[CronJobs] ⚠️ Dhan token expiring in ${minutesLeft} minutes! Sending Telegram alert...`);
        await sendTelegramAlert(
          `⚠️ <b>Trade Grow — Dhan Token Expiry Alert!</b>\n\n` +
          `🕐 Token expires in: <b>${minutesLeft} minutes</b>\n\n` +
          `🔑 Action required:\n` +
          `1. Login to <a href="https://login.dhan.co">https://login.dhan.co</a>\n` +
          `2. Copy your new Access Token\n` +
          `3. POST to: <code>/api/internal/update-dhan-token</code>\n\n` +
          `Body: <code>{"accessToken": "YOUR_NEW_TOKEN"}</code>`
        );
      }
    } else {
      const minutesLeft = getTokenExpiryMinutes(token);
      if (minutesLeft > 0) {
        console.log(`[CronJobs] ✅ Dhan token healthy. Expires in ${minutesLeft} minutes (~${(minutesLeft / 60).toFixed(1)}h).`);
      }
    }
  };

  checkNow();

  // Check every 30 minutes
  tokenExpiryCheckInterval = setInterval(checkNow, 30 * 60 * 1000);
  console.log('[CronJobs] 🔄 Dhan token expiry check interval started (every 30 minutes with TOTP auto-renewal).');
}

/**
 * Start all cron jobs. Call this from server/src/index.ts after DhanAdapter initializes.
 * @param getAccessToken - A function that returns the current Dhan access token (live)
 */
export function startCronJobs(getAccessToken: () => string) {
  console.log('[CronJobs] 🚀 Starting Trade Grow background cron jobs...');
  startTokenExpiryCheck(getAccessToken);
  scheduleMorningReminder(getAccessToken);
  startFyersAutoRenewalCheck();
}

let expirySettlementTimeout: NodeJS.Timeout | null = null;
let expirySettlementInterval: NodeJS.Timeout | null = null;

/**
 * Schedule the daily Contract Expiry Settlement engine run at 15:30 IST.
 * Settles all expiring derivative contracts across NRML/MIS/CNC.
 */
async function scheduleExpirySettlement() {
  let hour = 15, minute = 30;
  try {
    const row = await queryOne<any>(`SELECT value FROM system_settings WHERE key = 'EXPIRY_SETTLEMENT_TIME'`);
    const raw = (row?.value || '15:30').trim();
    const match = raw.match(/^(\d{1,2}):(\d{2})$/);
    if (match) {
      hour = parseInt(match[1], 10);
      minute = parseInt(match[2], 10);
    }
  } catch (err: any) {
    console.warn('[CronJobs] Failed to read EXPIRY_SETTLEMENT_TIME, defaulting to 15:30:', err.message);
  }

  const msUntilRun = getMsUntilISTTime(hour, minute);
  console.log(`[CronJobs] 📅 Contract Expiry Settlement scheduled in ${(msUntilRun / 1000 / 60 / 60).toFixed(1)}h (${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')} IST next trading day).`);

  expirySettlementTimeout = setTimeout(async () => {
    try {
      const { ExpirySettlementEngine } = await import('../trading/ExpirySettlementEngine');
      console.log('[CronJobs] 🚀 Executing scheduled 15:30 IST Contract Expiry Settlement...');
      await ExpirySettlementEngine.settleExpiredContracts();
    } catch (err: any) {
      console.error('[CronJobs] Contract Expiry Settlement run failed:', err.message);
    }
    // Re-schedule for the next trading day
    scheduleExpirySettlement();
  }, msUntilRun);
}

