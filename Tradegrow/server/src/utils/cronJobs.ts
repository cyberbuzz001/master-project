/**
 * Start the daily Contract Expiry Settlement scheduler and runtime background checks.
 */
export function startExpirySettlementJob() {
  scheduleExpirySettlement();

  // Periodic safety check: every 5 minutes during post-market (15:30–16:00 IST), verify no expired contracts remain open
  expirySettlementInterval = setInterval(async () => {
    try {
      const now = new Date();
      const istHours = ((now.getUTCHours() + 5) % 24) + ((now.getUTCMinutes() + 30) >= 60 ? 1 : 0) + (((now.getUTCMinutes() + 30) % 60) / 60);
      if (istHours >= 15.5 && istHours <= 16.5) {
        const { ExpirySettlementEngine } = await import('../trading/ExpirySettlementEngine');
        await ExpirySettlementEngine.settleExpiredContracts();
      }
    } catch (_) {}
  }, 5 * 60 * 1000);
}

/**
 * Gracefully stop all cron jobs (for clean server shutdown).
 */
export function stopCronJobs() {
  if (tokenExpiryCheckInterval) clearInterval(tokenExpiryCheckInterval);
  if (morningReminderTimeout) clearTimeout(morningReminderTimeout);
  if (fyersRenewalInterval) clearInterval(fyersRenewalInterval);
  if (misSquareOffTimeout) clearTimeout(misSquareOffTimeout);
  if (commodityMisSquareOffTimeout) clearTimeout(commodityMisSquareOffTimeout);
  if (expirySettlementTimeout) clearTimeout(expirySettlementTimeout);
  if (expirySettlementInterval) clearInterval(expirySettlementInterval);
  console.log('[CronJobs] 🛑 All cron jobs stopped.');
}

