  /**
   * Add a dynamic security mapping (option strikes etc.) with LRU-style eviction at SECURITY_MAP_MAX_SIZE.
   * Maintains bidirectional mapping so Dhan binary tick security IDs map back to canonical tokens in O(1).
   */
  public static addDynamicSecurityMapping(token: string, mapping: { segment: string; securityId: string }): void {
    if (!token || !mapping || !mapping.securityId) return;
    const cleanToken = token.trim();
    const cleanSecId = String(mapping.securityId).trim();

    if (!DhanAdapter.DHAN_SECURITY_MAP[cleanToken]) {
      // Evict oldest dynamic entries if we're at the cap
      while (DhanAdapter.dynamicSecurityMapKeys.length >= DhanAdapter.SECURITY_MAP_MAX_SIZE) {
        const oldest = DhanAdapter.dynamicSecurityMapKeys.shift();
        if (oldest) {
          const oldMap = DhanAdapter.DHAN_SECURITY_MAP[oldest];
          if (oldMap && oldMap.securityId) {
            DhanAdapter.reverseSecurityIdMap.delete(oldMap.securityId);
          }
          delete DhanAdapter.DHAN_SECURITY_MAP[oldest];
        }
      }
      DhanAdapter.dynamicSecurityMapKeys.push(cleanToken);
    }
    DhanAdapter.DHAN_SECURITY_MAP[cleanToken] = mapping;

    // Prefer canonical option/index tokens over raw numeric IDs or prefixed IDs
    const isGenericIdToken = /^\d+$/.test(cleanToken) || /^[A-Z]{3}_\d+$/.test(cleanToken);
    if (!isGenericIdToken) {
      DhanAdapter.reverseSecurityIdMap.set(cleanSecId, cleanToken);
    } else if (!DhanAdapter.reverseSecurityIdMap.has(cleanSecId)) {
      DhanAdapter.reverseSecurityIdMap.set(cleanSecId, cleanToken);
    }
  }

